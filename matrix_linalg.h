#ifndef MATRIX_LINALG_H
#define MATRIX_LINALG_H

#include "matrix.h"

// Метод Гаусса

/**
 * Решение СЛАУ методом Гаусса БЕЗ выбора ведущего элемента
 * @param A Матрица коэффициентов (n×n), НЕ модифицируется
 * @param b Вектор правых частей (n элементов)
 * @param x Выходной вектор решения (n элементов, должен быть выделен)
 * @return 0 при успехе, -1 при ошибке
 */
int matrix_solve_gauss(const Matrix *A, const void *b, void *x);

/**
 * Решение СЛАУ методом Гаусса С выбором главного элемента по столбцу
 * @param A Матрица коэффициентов (n×n), НЕ модифицируется
 * @param b Вектор правых частей (n элементов)
 * @param x Выходной вектор решения (n элементов, должен быть выделен)
 * @return 0 при успехе, -1 при ошибке (вырожденная матрица)
 */
int matrix_solve_gauss_pivot(const Matrix *A, const void *b, void *x);

// LU-РАЗЛОЖЕНИЕ

/**
 * LU-разложение матрицы (без перестановок)
 * Матрица A представляется как A = L × U, где:
 * - L — нижняя треугольная с единицами на диагонали
 * - U — верхняя треугольная
 * @param A Исходная матрица (n×n)
 * @param L Выходная матрица L (должна быть создана, n×n)
 * @param U Выходная матрица U (должна быть создана, n×n)
 * @return 0 при успехе, -1 при ошибке
 */
int matrix_lu_decompose(const Matrix *A, Matrix *L, Matrix *U);

/**
 * Решение системы с нижней треугольной матрицей (прямая подстановка)
 * L × x = b, где L — нижняя треугольная с единицами на диагонали
 * @param L Матрица L (n×n)
 * @param b Вектор правых частей (n элементов)
 * @param x Выходной вектор решения (n элементов)
 * @return 0 при успехе, -1 при ошибке
 */
int matrix_solve_lower_triangular(const Matrix *L, const void *b, void *x);

/**
 * Решение системы с верхней треугольной матрицей (обратная подстановка)
 * U × x = b, где U — верхняя треугольная
 * @param U Матрица U (n×n)
 * @param b Вектор правых частей (n элементов)
 * @param x Выходной вектор решения (n элементов)
 * @return 0 при успехе, -1 при ошибке
 */
int matrix_solve_upper_triangular(const Matrix *U, const void *b, void *x);

/**
 * Решение СЛАУ через LU-разложение: A×x = b → LU×x = b
 * 1. Ly = b (прямая подстановка)
 * 2. Ux = y (обратная подстановка)
 * @param L Матрица L из LU-разложения
 * @param U Матрица U из LU-разложения
 * @param b Вектор правых частей
 * @param x Выходной вектор решения
 * @return 0 при успехе, -1 при ошибке
 */
int matrix_solve_lu(const Matrix *L, const Matrix *U, const void *b, void *x);

// QR-РАЗЛОЖЕНИЕ (метод Грама-Шмидта)

/**
 * QR-разложение матрицы методом ортогонализации Грама-Шмидта
 * Матрица A представляется как A = Q × R, где:
 * - Q — ортогональная матрица (Qᵀ×Q = I)
 * - R — верхняя треугольная матрица
 * @param A Исходная матрица (m×n, m >= n)
 * @param Q Выходная матрица Q (m×n, должна быть создана)
 * @param R Выходная матрица R (n×n, должна быть создана)
 * @return 0 при успехе, -1 при ошибке
 */
int matrix_qr_decompose(const Matrix *A, Matrix *Q, Matrix *R);

/**
 * Решение СЛАУ через QR-разложение: A×x = b → QR×x = b → R×x = Qᵀ×b
 * @param Q Ортогональная матрица из QR-разложения
 * @param R Верхняя треугольная матрица из QR-разложения
 * @param b Вектор правых частей
 * @param x Выходной вектор решения
 * @return 0 при успехе, -1 при ошибке
 */
int matrix_solve_qr(const Matrix *Q, const Matrix *R, const void *b, void *x);

// ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ

/**
 * Проверка, что обработчик поддерживает вещественные числа
 * @param handler Обработчик типа
 * @return 1 если тип вещественный (DOUBLE), 0 иначе
 */
int is_floating_point_type(const TypeHandler *handler);

#endif // MATRIX_LINALG_H